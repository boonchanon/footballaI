#!/usr/bin/env node
const { rmSync, mkdirSync, writeFileSync } = require("node:fs")
const path = require("node:path")
const { spawnSync } = require("node:child_process")
const root = process.cwd()
const outDir = path.join(root, ".tmp-heatmap-analysis-tests")
rmSync(outDir, { recursive: true, force: true })
mkdirSync(outDir, { recursive: true })
const config = path.join(outDir, "tsconfig.json")
writeFileSync(config, JSON.stringify({ compilerOptions: { outDir, module: "commonjs", target: "es2022", moduleResolution: "node", skipLibCheck: true }, files: ["lib/heatmap-analysis.ts", "tests/heatmap-analysis.test.ts"].map((file) => path.join(root, file)) }))
const tsc = path.join(root, "node_modules", ".bin", process.platform === "win32" ? "tsc.cmd" : "tsc")
const compile = spawnSync(tsc, ["--project", config], { cwd: root, stdio: "inherit" })
const run = compile.status === 0 && spawnSync("node", ["--test", path.join(outDir, "tests", "heatmap-analysis.test.js")], { cwd: root, stdio: "inherit" })
rmSync(outDir, { recursive: true, force: true })
process.exit(compile.status || run.status || 0)
