#!/usr/bin/env node
const { rmSync, mkdirSync, writeFileSync } = require("node:fs")
const path = require("node:path")
const { spawnSync } = require("node:child_process")
const root = process.cwd()
const outDir = path.join(root, ".tmp-payment-safety-tests")
rmSync(outDir, { recursive: true, force: true })
mkdirSync(outDir, { recursive: true })
const config = path.join(outDir, "tsconfig.json")
writeFileSync(config, JSON.stringify({ compilerOptions: { outDir, rootDir: root, module: "commonjs", target: "es2022", moduleResolution: "node", esModuleInterop: true, skipLibCheck: true }, files: ["lib/server/tokens.ts", "lib/server/models.ts", "lib/server/payment-recipient.ts", "tests/payment-safety.test.ts"].map((file) => path.join(root, file)) }))
const tscScript = path.join(root, "node_modules", "typescript", "bin", "tsc")
const compile = spawnSync(process.execPath, [tscScript, "--project", config], { cwd: root, stdio: "inherit" })
const run = compile.status === 0 && spawnSync(process.execPath, ["--test", path.join(outDir, "tests", "payment-safety.test.js")], { cwd: root, stdio: "inherit" })
rmSync(outDir, { recursive: true, force: true })
process.exit(compile.status !== 0 ? compile.status ?? 1 : run.status ?? 1)
